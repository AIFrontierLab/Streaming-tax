"""Formatting helpers shared by the renderers (Markdown and LaTeX), with the paper's display conventions:

- absolute scores: the benchmark value (rounded to 2 decimals by the benchmark) printed with 1 decimal, exactly as
  the development report printed it; |x| < 0.05 prints as 0.0 (`absolute`);
- differences: '{:+.1f}'; Table 2 and the gap figure print |x| < 0.05 as +0.0 (`delta`); the master tables turn
  '-0.0' into '+0.0' (`master_delta`).
Python's format() rounds half to even on the binary value, which is what the published tables used."""
from __future__ import annotations

import csv
import io


def signed(value, digits: int = 1) -> str:
    return "–" if value is None else f"{value:+.{digits}f}"


def interval(low, high, digits: int = 1) -> str:
    return "–" if low is None else f"[{low:+.{digits}f}, {high:+.{digits}f}]"


def md_table(header: list[str], rows: list[list]) -> list[str]:
    def text(x):
        return "–" if x is None else str(x).replace("|", "\\|")
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header),
            *("| " + " | ".join(text(x) for x in r) + " |" for r in rows)]


def absolute(value, zero_below: float = 0.05) -> str:
    """An absolute score as the paper prints it: the 1-decimal report value, |x| < 0.05 -> 0.0, '--' if missing."""
    if value is None:
        return "--"
    shown = float(f"{value:.1f}")            # the development report's 1-decimal value the tables were built from
    shown = 0 if abs(shown) < zero_below else shown
    return f"{shown:.1f}"


def zeroed(value: float, zero_below: float = 0.05) -> float:
    return 0.0 if abs(value) < zero_below else value


def delta(value: float, zero_below: float = 0.05) -> str:
    """'+.1f' with |x| < 0.05 shown as +0.0 (Table 2, gap figure)."""
    return f"{zeroed(value, zero_below):+.1f}"


def master_delta(value: float) -> str:
    """'+.1f' with '-0.0' shown as '+0.0' (master tables)."""
    return f"{value:+.1f}".replace("-0.0", "+0.0")


def round4(x):
    """The 4-decimal rounding of the gap-figure / Table 2 data files (cells are formatted from these values)."""
    return None if x is None else round(float(x), 4)


def tex_row(cells) -> str:
    return " & ".join(str(x) for x in cells) + r" \\"


def tex_table(columns: str, header: list[str], rows: list[str], caption: str, label: str, size: str = "footnotesize",
              colsep: float = 3, comment: str = "% Generated by `streamreplace tables`; do not edit by hand.") -> str:
    """A booktabs table* in the layout of the paper's supplementary tables."""
    lines = [comment, r"\begin{table*}[t]", r"\centering",
             "\\caption{" + caption + "}", "\\label{" + label + "}", "\\" + size,
             "\\setlength{\\tabcolsep}{" + f"{colsep:g}" + "pt}", "\\begin{tabular}{" + columns + "}",
             r"\toprule", *header, r"\midrule", *rows, r"\bottomrule",
             r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines)


def to_csv(rows: list[dict], fields: list[str]) -> str:
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore", lineterminator="\n")
    writer.writeheader()
    for r in rows:
        writer.writerow(r)
    return buf.getvalue()


def tex_cells(text: str) -> list[list[str]]:
    """The cells of every tabular row of a generated LaTeX table (rows end with '\\\\'; rules and group headers
    are skipped). Used to compare tables cell by cell."""
    body = text.split(r"\midrule", 1)[-1].split(r"\bottomrule", 1)[0]
    out = []
    for line in body.splitlines():
        line = line.strip()
        if not line.endswith(r"\\") or line.startswith(r"\multicolumn") or line.startswith(r"\midrule"):
            continue
        out.append([c.strip() for c in line[:-2].split(" & ")])
    return out
