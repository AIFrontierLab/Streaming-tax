"""Table 2 of the paper (tables/gaps.tex): offline child-parent differences (C-P) in points.

Columns: the 7 headline image metrics, their unweighted mean (qualified cells included), HarmBench ASR reduction,
and the three prompt-robustness families. Cells come from gaps_json.build() (contrasts with the generation-cap
reruns merged). Shaded bold = Holm-significant in the main-text family (blue when the child is better, red when
worse); grey with a superscript = a qualified cell (* forced, dagger non-answer or artefact, double dagger more than
10% capped rows); |x| < 0.05 shows as +0.0."""
from __future__ import annotations

from .latex import zeroed

IMAGE_COLUMNS = (
    ("dynamath", "DynaMath"),
    ("mathvista", "MathVista"),
    ("mmbench", "MMBench"),
    ("mme_p", r"\shortstack{MME\\perception}"),
    ("mmmu", "MMMU"),
    ("mmstar", "MMStar"),
    ("scienceqa", "ScienceQA"),
)
ROBUST_FAMILIES = (("typo", "Typo"), ("para", "Paraphrase"), ("distraction", "Distraction"))
COLUMNS = (IMAGE_COLUMNS + (("image_mean", "Mean"), ("harmbench", r"\shortstack{HarmBench\\ASR red.}"))
           + tuple(("robust_" + key, label) for key, label in ROBUST_FAMILIES))
QUALIFICATIONS = (
    ("forced", "*"),
    ("non_answer", r"\dagger"),
    ("artifact", r"\dagger"),
    ("invalid", r"\ddagger"),
    ("truncation_pending", r"\ddagger"),
)
BLUE, RED, GREY = "D7E8F3", "F4DCD9", "8A939B"
CAPTION = (
    r"Offline child--parent differences ($C-P$) in points; positive values favor the child. "
    r"Shaded bold cells are Holm-significant within each benchmark family; "
    r"capped rows are rerun at 8,192 tokens (Supp. Sec.~\ref{supp:scoring}), and grey values with $^{\ddagger}$ still "
    r"have more than 10\% "
    r"truncated outputs in either arm. "
    r"MME perception is in percent of its maximum; Mean averages the seven image columns. "
    r"HarmBench reports ASR reduction, so negative values mean higher ASR in the child. "
    r"Prompt robustness reports, per perturbation type, the parent's accuracy drop minus the child's, "
    r"pooled over Video-MME and MMBench. "
    r"ThinkStream and MMDuet2 share a parent. "
    r"MME cognition and VisuLogic are in Supp. Table~\ref{tab:master-cp}; absolute scores and intervals are in "
    r"Supp. Secs.~\ref{supp:understanding}--\ref{supp:generalization}."
)


def number(value, symbols=""):
    return "$" + f"{value:+.1f}" + ("^{" + symbols + "}" if symbols else "") + "$"


def cell(record: dict | None) -> str:
    """Shade only Holm-significant cells; grey out qualified ones instead of hiding them."""
    if record is None or record.get("delta") is None:
        return "--"
    flags = set(record.get("flags", []))
    symbols = []
    for flag, symbol in QUALIFICATIONS:
        if flag in flags and symbol not in symbols:
            symbols.append(symbol)
    value = zeroed(record["delta"])
    if symbols:
        return r"\textcolor[HTML]{" + GREY + "}{" + number(value, "".join(symbols)) + "}"
    if record.get("holm_sig"):
        shade = r"\cellcolor[HTML]{" + (BLUE if value > 0 else RED) + "}"
        return shade + "$" + r"\mathbf{" + f"{value:+.1f}" + "}$"
    return number(value)


def records(data: dict) -> dict:
    """(child, column) -> cell record for every Table 2 column (robustness families split out, image mean added)."""
    keys = {key for key, _ in IMAGE_COLUMNS} | {"harmbench", "robust"}
    out = {}
    for record in data["cells"]:
        if record["panel"] != "offline" or record["column"] not in keys:
            continue
        if record["column"] != "robust":
            out[(record["child"], record["column"])] = record
            continue
        for family, _ in ROBUST_FAMILIES:
            if family in (record.get("all_families") or {}):
                value, low, high, _equivalent = record["all_families"][family]
                # Printed as plain numbers: none of these 18 accuracy contrasts is Holm-significant in the paper.
                out[(record["child"], "robust_" + family)] = {"delta": value, "ci": [low, high]}
    for child in data["children"]:
        image = [out.get((child, key), {}).get("delta") for key, _ in IMAGE_COLUMNS]
        if None not in image:
            # Unweighted mean of the seven image differences, qualified cells included.
            out[(child, "image_mean")] = {"delta": sum(image) / len(image)}
    return out


def latex(data: dict, names: dict) -> str:
    cells = records(data)
    lines = [
        "% Generated by `streamreplace tables` from gaps.json; do not edit by hand.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{" + CAPTION + "}",
        r"\label{tab:gaps}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}l" + "c" * len(COLUMNS) + "@{}}",
        r"\toprule",
        r" & \multicolumn{8}{c}{Image understanding} & Safety & \multicolumn{3}{c}{Prompt robustness} \\",
        r"\cmidrule(lr){2-9}\cmidrule(lr){10-10}\cmidrule(lr){11-13}",
        " & ".join(["Model"] + [label for _, label in COLUMNS]) + r" \\",
        r"\midrule",
    ]
    for child in data["children"]:
        lines.append(" & ".join([names.get(child, child)] + [cell(cells.get((child, key))) for key, _ in COLUMNS]) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}%", "}", r"\end{table*}", ""])
    return "\n".join(lines)


CSV_FIELDS = ["child", "column", "delta", "ci_low", "ci_high", "holm_sig", "tost3", "flags", "printed"]


def flat(data: dict) -> list[dict]:
    """One row per Table 2 cell with its unrounded value and the printed LaTeX (gaps.csv)."""
    cells = records(data)
    out = []
    for child in data["children"]:
        for key, _ in COLUMNS:
            r = cells.get((child, key)) or {}
            ci = r.get("ci") or [None, None]
            out.append({"child": child, "column": key, "delta": r.get("delta"), "ci_low": ci[0], "ci_high": ci[1],
                        "holm_sig": r.get("holm_sig"), "tost3": r.get("tost3"), "flags": "|".join(r.get("flags", [])),
                        "printed": cell(r or None)})
    return out
